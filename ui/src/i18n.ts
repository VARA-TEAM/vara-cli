const dictionaries: Record<Lang, Record<Key, string>> = { en, ar }

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  let s = dictionaries[lang][key] ?? en[key]
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v))
  return s
}

export const LangContext = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({ lang: 'en', setLang: () => {} })

export function useT(): (key: Key, vars?: Record<string, string | number>) => string {
  const { lang } = useContext(LangContext)
  return (key, vars) => translate(lang, key, vars)
}

const LANG_KEY = 'vara.lang'
export function savedLang(): Lang {
  try {
    const s = localStorage.getItem(LANG_KEY)
    if (s === 'ar' || s === 'en') return s
    return navigator.language?.toLowerCase().startsWith('ar') ? 'ar' : 'en'
  } catch {
    return 'en'
  }
}
export function applyLang(lang: Lang): void {
  document.documentElement.lang = lang
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr'
  try {
    localStorage.setItem(LANG_KEY, lang)
  } catch {
    /* not persisted */
  }
}

