#!/usr/bin/env node
/**
 * Builds the web interface (ui/) and embeds it in src/server/ui-assets.ts, so the
 * single-file release bundle carries the whole UI. Skipped when nothing changed.
 */
import { build } from 'esbuild'
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { basename, dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const uiDir = join(root, 'ui')
const out = join(root, 'src', 'server', 'ui-assets.ts')

function walk(dir) {
  return readdirSync(dir).flatMap((n) => {
    const p = join(dir, n)
    return statSync(p).isDirectory() ? walk(p) : [p]
  })
}

const files = existsSync(uiDir) ? walk(uiDir).filter((f) => !f.includes('node_modules')).sort() : []
const hash = createHash('sha256')
for (const f of files) hash.update(f.slice(root.length)).update(readFileSync(f))
hash.update(readFileSync(fileURLToPath(import.meta.url)))
const key = hash.digest('hex').slice(0, 16)

if (existsSync(out) && readFileSync(out, 'utf8').startsWith(`// ui-hash:${key}\n`)) process.exit(0)

mkdirSync(dirname(out), { recursive: true })
if (!files.some((f) => f.endsWith(join('src', 'main.tsx')))) {
  writeFileSync(out, `// ui-hash:${key}\nexport const uiAssets: { html: string | null; files: Record<string, { type: string; body: string }> } = { html: null, files: {} }\n`)
  process.exit(0)
}

const result = await build({
  entryPoints: { app: join(uiDir, 'src', 'main.tsx') },
  bundle: true,
  write: false,
  outdir: 'out',
  format: 'esm',
  target: ['es2020', 'chrome100', 'firefox100', 'safari15'],
  jsx: 'automatic',
  minify: true,
  sourcemap: false,
  legalComments: 'none',
  define: { 'process.env.NODE_ENV': '"production"' },
  loader: { '.svg': 'text' },
  logLevel: 'warning',
})

const assets = {}
for (const f of result.outputFiles) {
  const name = basename(f.path)
  assets[name] = { type: name.endsWith('.css') ? 'text/css; charset=utf-8' : 'text/javascript; charset=utf-8', body: f.text }
}
const html = readFileSync(join(uiDir, 'index.html'), 'utf8')
  .replace('%CSS%', assets['app.css'] ? '<link rel="stylesheet" href="/assets/app.css">' : '')

writeFileSync(
  out,
  `// ui-hash:${key}\n// GENERATED by scripts/build-ui.mjs from ui/ — do not edit, do not commit.\n` +
    `export const uiAssets: { html: string | null; files: Record<string, { type: string; body: string }> } = ${JSON.stringify({ html, files: assets })}\n`,
)
console.log(`ui built: ${Object.entries(assets).map(([n, a]) => `${n} ${(a.body.length / 1024).toFixed(0)} KB`).join(', ')}`)
