/** Writes ui/src/fonts.css: the bundled fonts as data URIs, so the interface needs no network and no extra routes. */
import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const b64 = (f) => readFileSync(join(root, 'ui', 'fonts', f)).toString('base64')
const face = (family, file, weight, range) =>
  `@font-face { font-family: "${family}"; font-style: normal; font-display: swap; font-weight: ${weight}; src: url(data:font/woff2;base64,${b64(file)}) format("woff2"); unicode-range: ${range}; }`
const LATIN = 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD'
const ARABIC = 'U+0600-06FF,U+0750-077F,U+08A0-08FF,U+FB50-FDFF,U+FE70-FEFF,U+200C-200E,U+2010-2011,U+204F,U+2E41,U+FE80-FEFC'
const css = [
  '/* Generated by scripts/gen-fonts.mjs. Bricolage Grotesque and IBM Plex Sans Arabic, SIL Open Font License 1.1 (ui/fonts/OFL-*.txt). */',
  face('Bricolage Grotesque', 'bricolage-latin.woff2', '200 800', LATIN),
  face('IBM Plex Sans Arabic', 'plex-arabic-400.woff2', 400, ARABIC),
  face('IBM Plex Sans Arabic', 'plex-arabic-600.woff2', '500 700', ARABIC),
  '',
].join('\n')
writeFileSync(join(root, 'ui', 'src', 'fonts.css'), css)
console.log(`ui/src/fonts.css ${(css.length / 1024).toFixed(0)} KB`)
