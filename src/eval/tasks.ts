/**
 * The evaluation tasks: small, deterministic coding problems.
 *
 * Every task is a tiny Node project (plain ESM JavaScript, no dependencies, no
 * network) that is materialised into a fresh temp directory, plus:
 *   - an objective in plain words (what a user would type),
 *   - an automated check: `node check.mjs` exits 0 only when the problem is
 *     really solved (the runner executes it itself, it never trusts the agent),
 *   - a reference solution as exact edits. A live model never sees it; the
 *     offline scripted model replays it, and the tests prove that each task
 *     FAILS before the edits and PASSES after them (so no task is unsolvable
 *     or already solved).
 *
 * Tasks are data in code (not a folder of files) so they ship inside the
 * compiled CLI and cannot drift from the runner.
 */

export type TaskCategory = 'bugfix' | 'feature' | 'refactor' | 'noisy'

export interface Edit {
  path: string
  oldString: string
  newString: string
}

export interface EvalTask {
  id: string
  title: string
  category: TaskCategory
  objective: string
  /** Files of the fixture project, relative paths (check.mjs and package.json included). */
  files: Record<string, string>
  /** The command whose exit code decides pass/fail. */
  checkCommand: string
  /** Reference solution: exact, unique-match edits. */
  solution: Edit[]
  /** Files the scripted model reads before editing. */
  reads: string[]
  /** For the one task with a long file: read only this window (1-based offset, limit). */
  readWindow?: { path: string; offset: number; limit: number }
}

const CHECK_COMMAND = 'node check.mjs'
const PACKAGE_JSON = '{\n  "name": "eval-fixture",\n  "private": true,\n  "type": "module"\n}\n'

/** Builds check.mjs: independent cases, a stable one-line verdict per case, exit code 1 on any failure. */
function checkScript(imports: string, cases: string, noiseLines = 0): string {
  const noise = noiseLines
    ? `for (let i = 0; i < ${noiseLines}; i++) console.log('ok   generated case ' + i + ' (2ms)')\n`
    : ''
  return (
    `import assert from 'node:assert/strict'\n${imports}\n` +
    `const failures = []\n` +
    `async function t(name, fn) {\n  try {\n    await fn()\n    console.log('ok   ' + name)\n  } catch (e) {\n    failures.push(name)\n    console.log('FAIL ' + name + ': ' + String(e.message).split('\\n')[0])\n  }\n}\n` +
    noise +
    `${cases}\n` +
    `if (failures.length) {\n  console.log(failures.length + ' failed')\n  process.exit(1)\n}\nconsole.log('all passed')\n`
  )
}

function make(spec: {
  id: string
  title: string
  category: TaskCategory
  objective: string
  src: Record<string, string>
  imports: string
  cases: string
  noise?: number
  solution: Edit[]
  reads?: string[]
  readWindow?: EvalTask['readWindow']
}): EvalTask {
  const files: Record<string, string> = { 'package.json': PACKAGE_JSON, ...spec.src, 'check.mjs': checkScript(spec.imports, spec.cases, spec.noise ?? 0) }
  return {
    id: spec.id,
    title: spec.title,
    category: spec.category,
    objective: spec.objective,
    files,
    checkCommand: CHECK_COMMAND,
    solution: spec.solution,
    reads: spec.reads ?? Object.keys(spec.src),
    ...(spec.readWindow ? { readWindow: spec.readWindow } : {}),
  }
}

/** A long module (about 1,300 lines) with one bug deep inside it. */
function longModule(): { text: string; bugLine: number } {
  const out: string[] = ['// Pricing rules, generated by hand over many years.', '']
  for (let i = 0; i < 160; i++) {
    out.push(`export function rule${i}(amount) {`)
    out.push(`  // rule ${i}: adjust the amount for the case number ${i}`)
    out.push(`  const base = Number(amount)`)
    out.push(`  const adjusted = base + ${i}`)
    out.push(`  return adjusted - ${i}`)
    out.push(`}`)
    out.push('')
  }
  out.push('export function applyDiscount(price, percent) {')
  out.push('  return price - price * percent')
  out.push('}')
  out.push('')
  const bugLine = out.length - 3 // the "return" line, 1-based = index + 1
  return { text: out.join('\n'), bugLine: bugLine + 1 }
}

